-- Marktbegleiter- und Preisdatenbank (Masterprompt 27.10.2026)
--
-- Eigenes, privates Schema „marktbegleiter“ im Projekt Grundfos-PIM. Vertraulich: kein Zugriff über die öffentliche API
-- (anon/authenticated), RLS auf allen Tabellen ohne Freigabe-Policies, Funktionen nur für interne Rollen.
-- Grundfos-Stamm (pim.*) wird nur gelesen; Marktpreise werden nie als eigene Einkaufs-/Verkaufspreise übernommen.
--
--  firmen          Marktbegleiter (Name, Domain, Land, Kontakt, Sortiment, Hersteller, aktiv, letzte Preisliste)
--  produkte        Produkt je Firma (Hersteller, MPN, EAN, Bezeichnung …) + Zuordnung zum Grundfos-Artikel mit Status
--  preise          jede Preisbeobachtung (Historie, nie überschrieben): netto/brutto, USt, Währung, EUR mit Kurs,
--                  Preiseinheit, Mindestmenge, Staffel, Versand, Lager, Lieferzeit, Gültigkeit, Quelle, Preisart, Import
--  importe         je eingelesene Datei: Zähler, Status, Fehlerprotokoll, erkannte Spalten
--  import_zeilen   Zwischenablage je Datei (Rohzeile + erkannte Felder + Ergebnis je Zeile)
--  ust_saetze, wechselkurse   Hilfstabellen (Kurs je Datum dokumentiert)
-- Übernahme: pim.wettbewerber → firmen (gleiche IDs), pim.marktpreis → produkte/preise (alte ID in alt_marktpreis_id).
-- pim.wettbewerber und pim.marktpreis bleiben unverändert bestehen.

