-- Historie: Preise werden nie geändert, nur neu erfasst
create or replace function marktbegleiter.preise_unveraenderlich()
returns trigger language plpgsql as $$
begin
  if (new.originalpreis, new.original_typ, new.waehrung, new.erfasst_am, new.produkt_id, new.firma_id, new.staffel_ab)
     is distinct from
     (old.originalpreis, old.original_typ, old.waehrung, old.erfasst_am, old.produkt_id, old.firma_id, old.staffel_ab) then
    raise exception 'Marktpreise sind Historie und werden nicht geändert – neuen Preis erfassen (Preis-ID %)', old.id;
  end if;
  return new;
end $$;
drop trigger if exists preise_unveraenderlich on marktbegleiter.preise;
create trigger preise_unveraenderlich before update on marktbegleiter.preise
  for each row execute function marktbegleiter.preise_unveraenderlich();

