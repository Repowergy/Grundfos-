create temp table _m on commit drop as
select m.*,
       coalesce(m.wettbewerber_id,
                (select f.id from marktbegleiter.firmen f where lower(f.name) = lower(m.shop) and f.land = m.land limit 1),
                (select f.id from marktbegleiter.firmen f where f.domain = marktbegleiter.domain_norm(m.url)
                  order by (f.land = m.land) desc limit 1)) as firma_id,
       a.artikelnummer as unsere_nr
  from pim.marktpreis m left join pim.artikel a on a.id = m.artikel_id;

insert into marktbegleiter.produkte (firma_id, hersteller, hersteller_norm, mpn, mpn_norm, bezeichnung, url, schluessel,
                                     vorschlag_artikel_id, matching_status, matching_hinweis)
select distinct on (x.firma_id, x.schluessel) x.firma_id, 'Grundfos', 'GRUNDFOS', x.mpn, marktbegleiter.nr_norm(x.mpn),
       x.typbezeichnung, x.url, x.schluessel, x.artikel_id, 'offen',
       'aus Recherche 27.10.2026: Warenkorb-Artikel ' || coalesce(x.unsere_nr, '?')
  from (select _m.*, coalesce(nullif(btrim(_m.artikelnummer_im_shop), ''), _m.unsere_nr) as mpn,
               'GRUNDFOS:' || marktbegleiter.nr_norm(coalesce(nullif(btrim(_m.artikelnummer_im_shop), ''), _m.unsere_nr)) as schluessel
          from _m where _m.firma_id is not null) x
 order by x.firma_id, x.schluessel, x.id
on conflict (firma_id, schluessel) do nothing;

insert into marktbegleiter.preise (firma_id, produkt_id, import_id, originalpreis, original_typ, waehrung, ust_satz,
            preis_netto, preis_brutto, wechselkurs, wechselkurs_datum, wechselkurs_quelle, preis_eur_netto, preis_eur_brutto,
            versand, versand_eur, lagerbestand, lieferbar, erfasst_am, quelle_url, quelldatei, preisart, bemerkung, alt_marktpreis_id)
select _m.firma_id, p.id, (select max(id) from marktbegleiter.importe where dateiname = 'Übernahme pim.marktpreis'),
       _m.preis_brutto, 'brutto', _m.waehrung, u.satz,
       round(_m.preis_brutto / (1 + u.satz / 100), 4), _m.preis_brutto,
       case when _m.waehrung = 'EUR' then 1 else round(_m.preis_eur / nullif(_m.preis_brutto, 0), 6) end,
       date '2026-10-27',
       case when _m.waehrung = 'EUR' then 'fest' else 'Annahme Recherche 27.10.2026 (nicht live verifiziert)' end,
       round(_m.preis_eur / (1 + u.satz / 100), 4), _m.preis_eur,
       _m.versand, case when _m.waehrung = 'EUR' then _m.versand else round(_m.versand * _m.preis_eur / nullif(_m.preis_brutto, 0), 2) end,
       _m.verfuegbarkeit,
       case when _m.verfuegbarkeit ~* '(nicht|kein|ausverkauft)' then false
            when _m.verfuegbarkeit ~* '(lager|verfügbar|sofort|lieferbar)' then true end,
       _m.datum, _m.url, 'pim.marktpreis: ' || coalesce(_m.quelle, ''), 'oeffentlich',
       'Recherche-Snippet, unverifiziert', _m.id
  from _m
  join marktbegleiter.produkte p on p.firma_id = _m.firma_id
   and p.schluessel = 'GRUNDFOS:' || marktbegleiter.nr_norm(coalesce(nullif(btrim(_m.artikelnummer_im_shop), ''), _m.unsere_nr))
  left join marktbegleiter.ust_saetze u on u.land = _m.land
on conflict do nothing;

