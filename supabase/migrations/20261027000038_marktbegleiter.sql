-- letzter Preis je Produkt (kleinste Staffel)
create or replace view marktbegleiter.v_letzter_preis with (security_invoker = true) as
select distinct on (pr.produkt_id) pr.*
  from marktbegleiter.preise pr
 order by pr.produkt_id, pr.erfasst_am desc, pr.staffel_ab, pr.id desc;

-- alle aktuellen Angebote je Grundfos-Artikel (Filter: hersteller, baureihe, land, artikelnummer)
create or replace view marktbegleiter.v_angebote with (security_invoker = true) as
select a.id as artikel_id, a.artikelnummer, p.hersteller_norm as hersteller, coalesce(p.baureihe, ag.gruppe) as baureihe,
       p.kategorie, f.id as firma_id, f.name as firma, f.land, f.domain,
       p.id as produkt_id, p.mpn, p.ean, p.bezeichnung, p.matching_status, p.url,
       l.preisart, l.waehrung, l.preis_netto, l.preis_brutto, l.preis_eur_netto, l.preis_eur_brutto,
       l.preis_eur_netto_stueck, l.versand_eur,
       l.preis_eur_brutto + coalesce(l.versand_eur, 0) as preis_eur_brutto_inkl_versand,
       l.lieferbar, l.lagerbestand, l.lieferzeit, l.mindestmenge, l.erfasst_am, l.quelle_url
  from marktbegleiter.v_letzter_preis l
  join marktbegleiter.produkte p on p.id = l.produkt_id
  join marktbegleiter.firmen f on f.id = l.firma_id
  left join pim.artikel a on a.id = p.artikel_id
  left join lateral (select g.code as gruppe from pim.artikel_gruppe x join pim.produktgruppe g on g.id = x.gruppe_id
                      where x.artikel_id = a.id limit 1) ag on true
 where f.aktiv;

-- Vergleich je Grundfos-Artikel und Land: günstigster Anbieter, Spanne
create or replace view marktbegleiter.v_preisvergleich with (security_invoker = true) as
select o.artikel_id, o.artikelnummer, o.land,
       count(*) as anbieter,
       min(o.preis_eur_netto) as min_netto_eur,
       percentile_cont(0.5) within group (order by o.preis_eur_netto) as median_netto_eur,
       max(o.preis_eur_netto) as max_netto_eur,
       min(o.preis_eur_brutto) as min_brutto_eur,
       min(o.preis_eur_brutto_inkl_versand) as min_brutto_inkl_versand_eur,
       (array_agg(o.firma order by o.preis_eur_netto))[1] as guenstigster_anbieter,
       round(100 * (max(o.preis_eur_netto) - min(o.preis_eur_netto)) / nullif(min(o.preis_eur_netto), 0), 1) as spanne_prozent,
       count(*) filter (where o.lieferbar) as lieferbar,
       max(o.erfasst_am) as stand
  from marktbegleiter.v_angebote o
 where o.artikel_id is not null and o.preis_eur_netto is not null
 group by o.artikel_id, o.artikelnummer, o.land;

-- Preisentwicklung je Firma und Produkt (Veränderung zum vorherigen Preis)
create or replace view marktbegleiter.v_preisentwicklung with (security_invoker = true) as
select pr.firma_id, f.name as firma, f.land, pr.produkt_id, p.artikel_id, p.mpn, p.bezeichnung, pr.staffel_ab, pr.erfasst_am,
       pr.preis_eur_netto,
       lag(pr.preis_eur_netto) over w as vorher_eur_netto,
       round(100 * (pr.preis_eur_netto - lag(pr.preis_eur_netto) over w) / nullif(lag(pr.preis_eur_netto) over w, 0), 1)
         as veraenderung_prozent
  from marktbegleiter.preise pr
  join marktbegleiter.firmen f on f.id = pr.firma_id
  join marktbegleiter.produkte p on p.id = pr.produkt_id
window w as (partition by pr.produkt_id, pr.staffel_ab order by pr.erfasst_am, pr.id);

-- Prüfliste: unklare Zuordnungen
create or replace view marktbegleiter.v_zuordnung_pruefen with (security_invoker = true) as
select p.id as produkt_id, f.name as firma, f.land, p.hersteller, p.mpn, p.ean, p.bezeichnung, p.matching_status,
       p.matching_hinweis, va.artikelnummer as vorschlag_artikelnummer,
       (select g.typbezeichnung from pim.v_artikel_de g where g.id = p.vorschlag_artikel_id) as vorschlag_typ
  from marktbegleiter.produkte p
  join marktbegleiter.firmen f on f.id = p.firma_id
  left join pim.artikel va on va.id = p.vorschlag_artikel_id
 where p.matching_status in ('vorschlag', 'kein_treffer');

-- alle Anbieter einer Grundfos-Pumpe
create or replace function marktbegleiter.anbieter(p_artikelnummer text, p_land text default null)
returns setof marktbegleiter.v_angebote
language sql stable set search_path = marktbegleiter, pim, public as $$
  select * from marktbegleiter.v_angebote
   where artikel_id = (select id from pim.artikel where hersteller_id = 1 and artikelnummer_norm = marktbegleiter.nr_norm(p_artikelnummer))
     and (p_land is null or land = upper(p_land))
   order by preis_eur_netto nulls last
$$;

